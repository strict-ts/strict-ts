import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from '@typescript/typescript6';
import { afterEach, describe, expect, test } from 'vitest';
import { deriveSchemas, run } from '../src/index.js';

const fixture = fileURLToPath(new URL('fixtures/shop/', import.meta.url));
const std = fileURLToPath(new URL('../../std/src/index.ts', import.meta.url));
const copies: string[] = [];
function project(): string {
  const directory = mkdtempSync(join(tmpdir(), 'strict-ts-derive-'));
  copies.push(directory);
  cpSync(fixture, directory, { recursive: true });
  return directory;
}
afterEach(() => {
  for (const directory of copies.splice(0)) rmSync(directory, { recursive: true, force: true });
});

const derive = (cwd: string, ...argv: readonly string[]) => {
  const out: string[] = [];
  const err: string[] = [];
  const code = run(argv, { cwd, out: (line) => out.push(line), err: (line) => err.push(line) });
  return { code, out, err };
};
/** What the compiler says of the files of a directory, under the strict options. */
const compile = (directory: string, ...files: readonly string[]): readonly string[] => {
  const program = ts.createProgram({
    rootNames: files.map((file) => join(directory, file)),
    options: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ESNext,
      moduleResolution: ts.ModuleResolutionKind.Bundler,
      lib: ['lib.es2022.d.ts'],
      types: [],
      noEmit: true,
      strict: true,
      exactOptionalPropertyTypes: true,
      noUncheckedIndexedAccess: true,
      paths: { '@strict-ts/std': [std] },
    },
  });
  return ts.getPreEmitDiagnostics(program).map((d) => `${d.file?.fileName.split('/').pop() ?? ''} ${ts.flattenDiagnosticMessageText(d.messageText, ' ').slice(0, 60)}`);
};
const from = (text: string, ...names: readonly string[]) => deriveSchemas(ts, ts.createSourceFile('types.ts', text, ts.ScriptTarget.Latest, true), './types.js', names);
const problems = (text: string) => {
  const result = from(text);
  return result.ok ? [] : result.error.map((problem) => `${problem.line}:${problem.column} ${problem.what}`);
};

describe('strict-ts-derive', () => {
  test('writes the schema of each exported type, the ones another names first', () => {
    const directory = project();
    expect(derive(directory, 'types.ts')).toEqual({ code: 0, out: [`${join(directory, 'types.schema.ts')}: CustomerIdSchema, QuantitySchema, LineSchema, OrderSchema`], err: [] });
    expect(readFileSync(join(directory, 'types.schema.ts'), 'utf8')).toBe(
      [
        '// Generated by strict-ts-derive from types.ts. Do not edit: change the types, and generate again.',
        '// Each schema is annotated with its type: the compiler refuses one that does not produce it.',
        "import { s } from '@strict-ts/std';",
        'import type { CustomerId, Line, Order, Quantity } from "./types.js";',
        '',
        'export const CustomerIdSchema: s.Schema<CustomerId> = s.branded(s.string, "CustomerId");',
        '',
        'export const QuantitySchema: s.Schema<Quantity> = s.positive(s.integer(s.number));',
        '',
        'export const LineSchema: s.Schema<Line> = s.object({',
        '  label: s.nonEmpty(s.string),',
        '  quantity: QuantitySchema,',
        '  gift: s.optional(s.boolean),',
        '});',
        '',
        'export const OrderSchema: s.Schema<Order> = s.object({',
        '  customer: CustomerIdSchema,',
        '  status: s.literal("open", "paid"),',
        '  lines: s.array(LineSchema),',
        '  notes: s.record(s.string),',
        '  placedAt: s.date,',
        '  "x-source": s.optional(s.literal("web", "shop")),',
        '});',
        '',
      ].join('\n'),
    );
  });

  test('what it writes compiles against the types, and stops compiling when a type changes', () => {
    const directory = project();
    derive(directory, 'types.ts');
    expect(compile(directory, 'types.ts', 'types.schema.ts')).toEqual([]);
    // A property is added to a type, and the schema is not generated again: the compiler says so, in the schema.
    const types = join(directory, 'types.ts');
    writeFileSync(types, readFileSync(types, 'utf8').replace("readonly status: 'open' | 'paid';", "readonly status: 'open' | 'paid';\n  readonly total: number;"));
    expect(compile(directory, 'types.ts', 'types.schema.ts').map((line) => line.split(' ')[0])).toEqual(['types.schema.ts']);
    // And so does `--check`, without compiling.
    expect(derive(directory, 'types.ts', '--check').code).toBe(1);
    derive(directory, 'types.ts');
    expect(derive(directory, 'types.ts', '--check')).toEqual({ code: 0, out: [], err: [] });
    expect(compile(directory, 'types.ts', 'types.schema.ts')).toEqual([]);
  });

  test('a choice between shapes, a value that may be missing, and what is not known yet', () => {
    const directory = project();
    writeFileSync(
      join(directory, 'types.ts'),
      [
        'export type Circle = { readonly kind: "circle"; readonly radius: number };',
        'export type Square = { readonly kind: "square"; readonly side: number };',
        'export type Drawing = {',
        '  readonly shape: Circle | Square;',
        '  readonly label: string | undefined;',
        '  readonly weight: number | "auto" | "none" | undefined;',
        '  readonly extra: unknown;',
        '  readonly tags?: readonly (string | number)[];',
        '};',
        '',
      ].join('\n'),
    );
    expect(derive(directory, 'types.ts').code).toBe(0);
    expect(readFileSync(join(directory, 'types.schema.ts'), 'utf8').split('\n').slice(15, 22)).toEqual([
      'export const DrawingSchema: s.Schema<Drawing> = s.object({',
      '  shape: s.union(CircleSchema, SquareSchema),',
      '  label: s.nullish(s.string),',
      '  weight: s.nullish(s.union(s.literal("auto", "none"), s.number)),',
      '  extra: s.unknown,',
      '  tags: s.optional(s.array(s.union(s.string, s.number))),',
      '});',
    ]);
    expect(compile(directory, 'types.ts', 'types.schema.ts')).toEqual([]);
  });

  test('only the types that are named, with those they name', () => {
    const result = from('export type A = { readonly b: B };\nexport type B = { readonly n: number };\nexport type C = string;\n', 'A');
    expect(result.ok && result.value.types).toEqual(['B', 'A']);
  });

  test('says what it cannot follow, with its place, and writes nothing then', () => {
    expect(
      problems(
        [
          'export type Shape = { readonly kind: "circle"; readonly r: number } | null;',
          'export type Bag = { readonly items: string[] };',
          'export type Tree = { readonly children: readonly Tree[] };',
          'export type Box<T> = { readonly value: T };',
          'export type Maybe = { readonly value: undefined };',
          'export type Pair = { readonly both: readonly [number, number] };',
          'export type Uses = { readonly other: Elsewhere; readonly hidden: Hidden };',
          'type Hidden = { readonly n: number };',
          'export type Calls = { run(): void };',
          '',
        ].join('\n'),
      ),
    ).toEqual([
      '1:71 `null`: write `| undefined`, which is read from a `null` as well',
      '2:37 a mutable array: a parsed value is read-only, write `readonly T[]`',
      '3:50 the type `Tree`, which contains itself',
      '4:13 the type `Box` takes parameters',
      '5:39 a type the standard library has no schema for',
      '6:37 a type the standard library has no schema for',
      '7:38 the type `Elsewhere`: it is not declared in this file, or it takes arguments',
      '8:6 the type `Hidden` is not exported: the generated module cannot name it',
      '9:23 a member that is not a property with a type (a method, an index signature)',
    ]);
    const directory = project();
    writeFileSync(join(directory, 'types.ts'), 'export type Bag = { readonly items: string[] };\n');
    expect(derive(directory, 'types.ts')).toEqual({ code: 2, out: [], err: ['strict-ts-derive: types.ts:1:37 cannot follow a mutable array: a parsed value is read-only, write `readonly T[]`'] });
  });
});
