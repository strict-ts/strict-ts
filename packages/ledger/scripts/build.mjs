// Builds the generated part of the effects ledger and writes it where core reads it.
//
//   node scripts/build.mjs            runs every function of the library and writes the ledger
//   node scripts/build.mjs --check    does the same in memory and fails when the verdicts differ from what is written
//   node scripts/build.mjs --report   prints what was observed, and writes nothing
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { derive } from './derive.mjs';
import { fuzz } from './fuzz.mjs';
import { readLibrary } from './library.mjs';
import { CLASS_KINDS, operators } from './operators.mjs';
import { analyse, declaredNames, throwingGetters } from './spec.mjs';

const target = fileURLToPath(new URL('../../core/src/effects/generated.ts', import.meta.url));
const args = new Set(process.argv.slice(2));

const library = readLibrary();
const observed = await fuzz(library);

// What the specification says, read from the facts kept in the repo (`node scripts/spec-facts.mjs` rewrites them).
const read = (path) => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));
const declared = new Set(library.map((entry) => entry.name));
const specified = new Map();
const verdictsOfSpec = analyse(read('../spec/facts.json').clauses);
for (const [specName, verdict] of verdictsOfSpec) {
  for (const name of declaredNames(specName)) if (declared.has(name)) specified.set(name, verdict);
}
const acknowledged = read('../acknowledged.json');
const { entries, quiet, contradictions, summary } = derive(library, observed, specified, acknowledged);

// A function the specification gives no way to throw, and that threw: the reading of the specification is wrong
// there. Each case must be understood and written down; one that is not fails the build.
const unexplained = contradictions.filter((found) => found.acknowledged === undefined);
for (const found of unexplained) console.error(`contradiction: ${found.name} threw (${found.seen}) and the specification (${found.spec}) gives it no way to`);
const stale = Object.keys(acknowledged).filter((name) => !contradictions.some((found) => found.name === name));
for (const name of stale) console.error(`acknowledged.json names ${name}, which no longer contradicts: remove it`);
if (unexplained.length > 0 || stale.length > 0) process.exitCode = 1;

const quote = (text) => `'${text.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : quote(name));
const write = (entry) => {
  const fields = [
    `verdict: ${quote(entry.verdict)}`,
    ...(entry.why === undefined ? [] : [`why: ${quote(entry.why)}`]),
    ...(entry.below === undefined ? [] : [`below: ${entry.below}`]),
    ...(entry.atLeast === undefined ? [] : [`atLeast: ${entry.atLeast}`]),
    ...(entry.unprintable === undefined ? [] : ['unprintable: true']),
    ...(entry.detached === undefined ? [] : ['detached: true']),
    `evidence: { ${[`runs: ${entry.evidence.runs}`, ...(entry.evidence.spec === undefined ? [] : [`spec: ${quote(entry.evidence.spec)}`]), ...(entry.evidence.example === undefined ? [] : [`example: ${quote(entry.evidence.example)}`])].join(', ')} }`,
  ];
  return `  ${key(entry.name)}: { ${fields.join(', ')} },`;
};
const operatorTable = operators().table;
const text = [
  '// Generated by packages/ledger (`pnpm --filter @strict-ts/ledger build`). Do not edit: change the generator.',
  '// Each entry was derived from running the function on generated values (`runs`) and from reading the ECMAScript',
  '// specification (`spec`, the clause). `total` needs both to agree.',
  "import type { Ledger } from './ledger.js';",
  '',
  'export const generated: Ledger = {',
  ...entries.map(write),
  '};',
  '',
  '/** The functions that were run and never threw, with how many times: evidence for an entry, not a verdict. */',
  'export const observed: Readonly<Record<string, number>> = {',
  ...Object.entries(quiet).map(([name, runs]) => `  ${key(name)}: ${runs},`),
  '};',
  '',
  '/**',
  ' * The operators that threw on operands the compiler accepts, by the operator and the kinds of its operands;',
  ' * `template` stands for `${…}`. Every operator was run on every pair of kinds: one that is not here did not throw.',
  ' */',
  'export const operators: Readonly<Record<string, string>> = {',
  ...Object.entries(operatorTable).map(([combination, why]) => `  ${quote(combination)}: ${quote(why)},`),
  '};',
  '',
  '/**',
  ' * The properties of the library that run code when read and can throw there, by the specification; every accessor',
  ' * of the specification was read, and one that is not here has no way to throw on the object it is read from.',
  ' */',
  'export const getters: Readonly<Record<string, string>> = {',
  ...Object.entries(throwingGetters(verdictsOfSpec)).filter(([, found]) => found.detached !== true).map(([name, found]) => `  ${quote(name)}: ${quote(`throws a ${/^(?:via \w+: )?(\w+):/.exec(found.why)?.[1] ?? 'failure'} by the specification (${found.spec})`)},`),
  '};',
  '',
  '/** The same, for those that throw only on a buffer that was detached. */',
  `export const gettersWhenDetached: readonly string[] = [${Object.entries(throwingGetters(verdictsOfSpec)).filter(([, found]) => found.detached === true).map(([name]) => quote(name)).join(', ')}];`,
  '',
  '/** The classes of the library that are a kind of operand of their own, told by the name of the type. */',
  `export const operandClasses: readonly string[] = [${CLASS_KINDS.map(quote).join(', ')}];`,
  '',
].join('\n');

if (args.has('--report')) {
  console.log(JSON.stringify(summary, undefined, 1));
} else if (args.has('--check')) {
  // The verdicts, not the examples: the text of an error may change with the version of the engine.
  const combinations = (source) => [...source.matchAll(/^  '([^']+)': 'throws /gm)].map((m) => m[1]).join('\n');
  const verdicts = (source) => combinations(source) + [...source.matchAll(/^  (\S+): \{ verdict: '(\w+)'(?:, why: '[^']*')?(, below: \d+)?(, atLeast: \d+)?(, unprintable: true)?(, detached: true)?/gm)].map((m) => m.slice(1).join(' ')).join('\n');
  if (verdicts(readFileSync(target, 'utf8')) !== verdicts(text)) {
    console.error('The generated effects ledger is not what the generator gives now: run `pnpm --filter @strict-ts/ledger build` and read the difference.');
    process.exitCode = 1;
  } else {
    console.log(`ledger: as generated (${entries.length} entries)`);
  }
} else {
  writeFileSync(target, text);
  console.log(`ledger: ${entries.length} entries written; ${JSON.stringify(summary.counts)}`);
}
