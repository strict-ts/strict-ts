const LISTS = 600;
const SEED = 20261011;

/** A sequence of numbers from 0 to 1 that is the same at every run. */
function sequence(seed) {
  let state = seed >>> 0;
  const next = () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let mixed = Math.imul(state ^ (state >>> 15), 1 | state);
    mixed = (mixed + Math.imul(mixed ^ (mixed >>> 7), 61 | mixed)) ^ mixed;
    return ((mixed ^ (mixed >>> 14)) >>> 0) / 4294967296;
  };
  const whole = (below) => Math.floor(next() * below);
  const pick = (list) => list[whole(list.length)];
  const many = (least, most, make) => Array.from({ length: least + whole(most - least + 1) }, make);
  return { next, whole, pick, many };
}

// Every kind of character a text can hold: what a shape lets through of these is what the browser is asked about.
const ODD = ['', ' ', '\t', '\n', '\f', '\r', '\0', ' ', ' ', '\ud800', '\udc00', 'é', '😀', '"', "'", '\\', '<', '>', '&', '%', '#', '.', ',', ':', '(', ')', '[', ']', '=', '-', '_', '*', '+', '~', '|', '^', '$', '/', '{', '}', ';', '@', '!', '?'];
const LETTERS = [...'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'];
const DIGITS = [...'0123456789'];

function candidates(shape, random) {
  const noise = () => random.many(0, 8, () => random.pick(random.next() < 0.5 ? ODD : random.next() < 0.7 ? LETTERS : DIGITS)).join('');
  const word = (from) => random.many(1, 6, () => random.pick(from)).join('');
  const ident = () => `${random.pick(['', '', '-'])}${random.pick([...LETTERS, '_'])}${random.many(0, 6, () => random.pick([...LETTERS, ...DIGITS, '_', '-'])).join('')}`;
  const spaces = () => random.pick(['', '', ' ', '  ']);
  const lower = LETTERS.slice(0, 26);
  const name = () => `${random.pick(lower)}${random.many(0, 5, () => random.pick([...lower, ...DIGITS])).join('')}${random.many(0, 2, () => `-${word([...lower, ...DIGITS])}`).join('')}`;
  switch (shape) {
    case 'token':
      return random.next() < 0.5 ? noise() : random.many(1, 10, () => random.pick([...LETTERS, ...DIGITS, ...ODD.filter((odd) => !/^[\t\n\f\r ]?$/.test(odd))])).join('');
    case 'text':
      return noise();
    case 'element-name':
      return random.next() < 0.3 ? noise() : random.next() < 0.3 ? random.pick(['div', 'span', 'canvas', 'a', 'button', 'script', 'iframe', 'img', 'template', 'svg', 'html', 'body', 'input', 'object', 'embed', 'style', 'link']) : name();
    case 'header-name':
      return random.next() < 0.3 ? noise() : random.next() < 0.3 ? random.pick(['authorization', 'Content-Type', 'ETag', 'x-forwarded-for', 'Set-Cookie', 'cookie', 'host', 'TE', 'X-1']) : `${word([...LETTERS, ...DIGITS]).replace(/^\d+/, 'h')}${random.many(0, 3, () => `-${word([...LETTERS, ...DIGITS])}`).join('')}`;
    case 'attribute-name':
      return random.next() < 0.3 ? noise() : random.next() < 0.1 ? 'role' : `${random.pick(['aria', 'data'])}-${name()}`;
    case 'selector': {
      if (random.next() < 0.15) return noise();
      const quoted = () => random.pick([`"${word([...LETTERS, ...DIGITS, ' ', '-', "'", '#', '.', '['])}"`, `'${word([...LETTERS, ...DIGITS, ' ', '-', '"', ']', ','])}'`, ident()]);
      const attribute = () => `[${ident()}${random.next() < 0.5 ? '' : `${random.pick(['', '~', '|', '^', '$', '*'])}=${quoted()}`}]`;
      const part = () => random.pick([() => `#${ident()}`, () => `.${ident()}`, attribute])();
      const compound = () => (random.next() < 0.5 ? `${random.pick([ident(), '*', 'div', 'button'])}${random.many(0, 3, part).join('')}` : random.many(1, 3, part).join(''));
      const complex = () => `${compound()}${random.many(0, 3, () => `${random.pick([' ', ' ', `${spaces()}>${spaces()}`, `${spaces()}+${spaces()}`, `${spaces()}~${spaces()}`])}${compound()}`).join('')}`;
      return `${spaces()}${complex()}${random.many(0, 2, () => `${spaces()},${spaces()}${complex()}`).join('')}${spaces()}`;
    }
    case 'colour': {
      if (random.next() < 0.15) return noise();
      const hex = () => `#${Array.from({ length: random.pick([3, 4, 6, 8]) }, () => random.pick([...'0123456789abcdefABCDEF'])).join('')}`;
      const byte = () => String(random.pick([0, 1, 9, 80, 128, 255, 256, 999, random.whole(1000)])).padStart(random.pick([1, 1, 2, 3]), '0');
      const alpha = () => random.pick(['0', '1', '.5', '0.25', '0.0', '12', '1.50', '007', String(random.next()).slice(0, 2 + random.whole(8))]);
      const rgb = () => `${random.pick(['rgb', 'rgba'])}(${spaces()}${byte()}${spaces()},${spaces()}${byte()}${spaces()},${spaces()}${byte()}${spaces()}${random.next() < 0.5 ? '' : `,${spaces()}${alpha()}${spaces()}`})`;
      return random.next() < 0.4 ? hex() : rgb();
    }
    case 'unit':
      return random.pick([0, -0, 1, 0.5, Number.MIN_VALUE, 1 - Number.EPSILON, random.next(), random.next(), -1, 2, Number.NaN, Number.POSITIVE_INFINITY]);
    case 'flag':
      return random.next() < 0.5;
    case 'response-init': {
      const status = () => (random.next() < 0.7 ? 200 + random.whole(400) : random.pick([0, 99, 100, 101, 199, 204, 205, 304, 600, 999, 1000, -1, 200.5, Number.NaN, Number.POSITIVE_INFINITY, '200']));
      const held = () => (random.next() < 0.25 ? noise() : random.many(0, 12, () => String.fromCharCode(0x20 + random.whole(0x5f))).join(''));
      const headers = () => Object.fromEntries(random.many(0, 3, () => [candidates('header-name', random), held()]));
      const init = {};
      if (random.next() < 0.8) init.status = status();
      if (random.next() < 0.6) init.headers = headers();
      if (random.next() < 0.1) init.statusText = noise();
      return init;
    }
    default:
      return undefined;
  }
}

/** Lists of arguments that have the shapes of an entry, of every length its types accept. */
function listsFor(entry, random) {
  const lists = [];
  let tried = 0;
  const wanted = entry.lists ?? LISTS;
  while (lists.length < wanted && tried++ < wanted * 200) {
    const most = entry.rest === undefined ? entry.shapes.length : entry.shapes.length + 3;
    const length = entry.least + random.whole(most - entry.least + 1);
    const list = Array.from({ length }, (_, index) => candidates(entry.shapes[index] ?? entry.rest, random));
    if (list.every((value, index) => hasShape(entry.shapes[index] ?? entry.rest, value))) lists.push(list);
  }
  return lists;
}

// Runs in the page: calls each function on each of its receivers with each list, and says which calls threw.
const PAGE = `
const RECEIVERS = {
  tokens: () => {
    const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    const element = document.body.appendChild(document.createElement('div'));
    element.className = 'a b';
    return [element.classList, document.createElement('span').classList, svg.classList, document.createElement('a').relList, document.createElement('iframe').sandbox, document.createElement('output').htmlFor];
  },
  documents: () => [document, document.implementation.createHTMLDocument('x'), new DOMParser().parseFromString('<a/>', 'application/xml')],
  elements: () => {
    const root = document.body.appendChild(document.createElement('div'));
    root.innerHTML = '<p class="a" id="b" data-x="1"><span role="x">t</span></p><input><button></button><canvas></canvas>';
    // Not the root of the page: what is written on it stays, and a text that is not well formed there kills the
    // browser when it prints the page for the driver.
    return [root, ...root.querySelectorAll('*'), document.createElement('div'), document.createElementNS('http://www.w3.org/2000/svg', 'path'), document.implementation.createHTMLDocument('x').documentElement];
  },
  parents: () => {
    const root = document.body.appendChild(document.createElement('div'));
    root.innerHTML = '<p class="a" id="b" data-x="1"><span role="x">t</span></p>';
    const fragment = document.createDocumentFragment();
    fragment.append(document.createElement('i'));
    return [document, root, fragment, document.createElement('template').content, new DOMParser().parseFromString('<a><b/></a>', 'application/xml')];
  },
  headers: () => [new Headers(), new Headers({ 'content-type': 'text/plain', cookie: 'a=b' }), new Request('https://example.test/', { headers: { authorization: 'Basic eA==' } }).headers, new Response('x').headers, Response.error().headers],
  // A constructor is called on nothing.
  none: () => [undefined],
  gradients: () => {
    const context = document.createElement('canvas').getContext('2d');
    return [context.createLinearGradient(0, 0, 1, 1), context.createRadialGradient(0, 0, 1, 2, 2, 3), new OffscreenCanvas(2, 2).getContext('2d').createLinearGradient(0, 0, 1, 0)];
  },
};
const results = [];
for (const job of JOBS) {
  const member = job.name.slice(job.name.indexOf('.') + 1);
  const result = { name: job.name, runs: 0, threw: [] };
  for (const list of job.lists) {
    // Made again for each list: a call changes what it is made on.
    for (const receiver of RECEIVERS[job.on]()) {
      result.runs++;
      try {
        if (member === 'new') new globalThis[job.name.slice(0, job.name.indexOf('.'))](...list);
        else receiver[member](...list);
      } catch (error) {
        if (result.threw.length < 5) result.threw.push((receiver === undefined ? 'new' : receiver.constructor.name) + ' · ' + JSON.stringify(list) + ' → ' + (error && error.name));
      }
    }
    document.body.replaceChildren();
  }
  results.push(result);
}
const out = document.createElement('script');
out.type = 'application/json';
out.id = 'strict-ts-result';
out.textContent = JSON.stringify(results).replaceAll('<', '\\\\u003c');
document.documentElement.appendChild(out);
`;

const random = sequence(SEED);
// JSON has no way to write -0, NaN or an infinity: a number travels as text, and an object as its members, so that
// the two are told apart.
const packed = (value) =>
  typeof value === 'number' ? { number: Object.is(value, -0) ? '-0' : String(value) } : value !== null && typeof value === 'object' ? { members: Object.entries(value).map(([name, held]) => [name, packed(held)]) } : value;
const asked = process.env.SHAPES_ONLY?.split(',');
const jobs = TABLE.filter((entry) => asked === undefined || asked.includes(entry.name)).map((entry) => ({ name: entry.name, on: entry.on, lists: listsFor(entry, random).map((list) => list.map(packed)) }));
const work = mkdtempSync(join(tmpdir(), 'strict-ts-dom-shapes-'));
const file = join(work, 'page.html');
const data = JSON.stringify(jobs).replaceAll('<', '\\u003c');
writeFileSync(
  file,
  `<!doctype html><html><head><meta charset="utf-8"></head><body><script type="module">\nconst unpacked = (value) => (value === null || typeof value !== 'object' ? value : Array.isArray(value) ? value.map(unpacked) : 'number' in value ? Number(value.number) : 'members' in value ? Object.fromEntries(value.members.map(([name, held]) => [name, unpacked(held)])) : Object.fromEntries(Object.entries(value).map(([name, held]) => [name, unpacked(held)])));\nconst JOBS = unpacked(JSON.parse(${JSON.stringify(data)}));\n${PAGE}\n</script></body></html>`,
);
const results = await new Promise((resolve) => {
  execFile(chrome, ['--headless', '--no-sandbox', '--disable-gpu', '--virtual-time-budget=60000', '--dump-dom', `file://${file}`], { timeout: 120000, maxBuffer: 256 * 1024 * 1024 }, (_error, stdout) => {
    const found = /<script type="application\/json" id="strict-ts-result">([\s\S]*?)<\/script>/.exec(stdout ?? '');
    resolve(found === null ? undefined : JSON.parse(found[1].replaceAll('&lt;', '<').replaceAll('&gt;', '>').replaceAll('&amp;', '&')));
  });
});
rmSync(work, { recursive: true, force: true });
if (results === undefined) {
  console.error('dom-shapes: the page gave nothing back.');
  process.exit(2);
}

const contradicted = results.filter((result) => result.threw.length > 0 || result.runs === 0);
for (const result of contradicted) console.error(`dom-shapes: ${result.name} ${result.runs === 0 ? 'was not called' : `threw on arguments that have its shapes:\n  ${result.threw.join('\n  ')}`}`);
if (contradicted.length > 0) process.exit(1);

const quote = (text) => `'${text.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
const text = [
  '// Generated by packages/ledger (`CHROME=… node packages/ledger/scripts/dom-shapes.mjs`). Do not edit: change the',
  '// table there. The shapes of written arguments on which these functions of the DOM were called in a browser, and',
  '// never threw.',
  "import type { Written } from './ledger.js';",
  '',
  'export const domWritten: Readonly<Record<string, Written>> = {',
  ...TABLE.map((entry) => {
    const runs = results.find((result) => result.name === entry.name)?.runs ?? 0;
    const rest = entry.rest === undefined ? '' : ` rest: ${quote(entry.rest)},`;
    return `  ${quote(entry.name)}: { shapes: [${entry.shapes.map(quote).join(', ')}],${rest} clause: ${quote(entry.clause)}, runs: ${runs} },`;
  }),
  '};',
  '',
].join('\n');
if (process.argv.includes('--report')) console.log(results.map((result) => `${result.name}: ${result.runs} calls, none threw`).join('\n'));
else {
  writeFileSync(target, text);
  console.log(`dom-shapes: ${TABLE.length} functions, ${results.reduce((total, result) => total + result.runs, 0)} calls, none threw`);
}
